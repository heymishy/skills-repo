test('assemblyGeneratesAllFourTargetFiles_fromOneSource', () => {
  const tmp = mktmp();
  const ctxFile = writeTmpContext('meta:\n  name: "fixture-no-harness-preference"\n');
  try {
    const result = runAssembly(tmp, [
      '--skills-repo-path', ROOT,
      '--ref', 'rb-s3-test-ref',
      '--context', ctxFile,
      '--all-harnesses',
    ]);
    assert.strictEqual(result.status, 0, `assembly script exited ${result.status}: ${result.stderr}`);

    const files = readHarnessFiles(tmp);
    for (const rel of HARNESS_FILES) {
      assert.ok(files[rel] !== null, `expected ${rel} to be generated`);
    }
    const reference = files[HARNESS_FILES[0]];
    for (const rel of HARNESS_FILES.slice(1)) {
      assert.ok(files[rel].equals(reference), `${rel} is not byte-identical to ${HARNESS_FILES[0]}`);
    }
  } finally {
    rmtmp(tmp);
    try { fs.unlinkSync(ctxFile); } catch (_) {}
  }
});

test('assemblyPreservesExistingBehaviourForGithubVcsType', () => {
  const tmp = mktmp();
  try {
    // No --all-harnesses — this must exercise the exact pre-existing default
    // code path (vcs.type: github → single .github/copilot-instructions.md).
    const result = runAssembly(tmp, [
      '--skills-repo-path', ROOT,
      '--ref', 'rb-s3-test-ref',
      '--context', CONTEXT_GITHUB_FIXTURE,
    ]);
    assert.strictEqual(result.status, 0, `assembly script exited ${result.status}: ${result.stderr}`);

    const githubOut = path.join(tmp, '.github', 'copilot-instructions.md');
    assert.ok(fs.existsSync(githubOut), '.github/copilot-instructions.md should still be generated by default');

    for (const rel of ['CLAUDE.md', 'AGENTS.md', '.cursorrules']) {
      assert.ok(!fs.existsSync(path.join(tmp, rel)),
        `${rel} should NOT be generated without --all-harnesses — default behaviour must be unchanged`);
    }
  } finally {
    rmtmp(tmp);
  }
});

test('sourceChangeTriggersRegenerationOfAllFour', () => {
  const tmp = mktmp();
  const domainV1 = path.join(os.tmpdir(), `rb-s3-domain-v1-${Date.now()}.md`);
  const domainV2 = path.join(os.tmpdir(), `rb-s3-domain-v2-${Date.now()}.md`);
  const ctxFile = writeTmpContext('meta:\n  name: "fixture-source-change"\n');
  fs.writeFileSync(domainV1, '# Domain layer\n\nRB-S3-VERSION-1-MARKER\n', 'utf8');
  fs.writeFileSync(domainV2, '# Domain layer\n\nRB-S3-VERSION-2-MARKER\n', 'utf8');
  try {
    const r1 = runAssembly(tmp, [
      '--skills-repo-path', ROOT,
      '--ref', 'rb-s3-test-ref',
      '--context', ctxFile,
      '--domain-layer', domainV1,
      '--all-harnesses',
    ]);
    assert.strictEqual(r1.status, 0, `first assembly run exited ${r1.status}: ${r1.stderr}`);
    const v1Files = readHarnessFiles(tmp);
    for (const rel of HARNESS_FILES) {
      assert.ok(v1Files[rel].toString('utf8').includes('RB-S3-VERSION-1-MARKER'), `${rel} missing v1 marker`);
    }

    const r2 = runAssembly(tmp, [
      '--skills-repo-path', ROOT,
      '--ref', 'rb-s3-test-ref',
      '--context', ctxFile,
      '--domain-layer', domainV2,
      '--all-harnesses',
    ]);
    assert.strictEqual(r2.status, 0, `second assembly run exited ${r2.status}: ${r2.stderr}`);
    const v2Files = readHarnessFiles(tmp);
    for (const rel of HARNESS_FILES) {
      const content = v2Files[rel].toString('utf8');
      assert.ok(content.includes('RB-S3-VERSION-2-MARKER'), `${rel} was not regenerated with the v2 marker`);
      assert.ok(!content.includes('RB-S3-VERSION-1-MARKER'), `${rel} is stale — still contains the v1 marker`);
    }
  } finally {
    rmtmp(tmp);
    try { fs.unlinkSync(ctxFile); } catch (_) {}
    try { fs.unlinkSync(domainV1); } catch (_) {}
    try { fs.unlinkSync(domainV2); } catch (_) {}
  }
});

