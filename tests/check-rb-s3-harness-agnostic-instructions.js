console.log('\n[rb-s3] Integration tests\n');

test('rbS3BuildsOnRbS1AndRbS2Output', () => {
  const { runInit } = require('../cli/lib/init');
  const tmp = mktmp();
  try {
    runInit(tmp, {});
    // Skills-repo-path points at the freshly-bootstrapped target itself —
    // after rb-s1/rb-s2, its .github/skills holds the real 46-skill set,
    // not a fixture, so this proves the assembly extension reads real
    // skill content, not placeholders.
    const contextFile = path.join(tmp, 'context.yml');
    const result = runAssembly(tmp, [
      '--skills-repo-path', tmp,
      '--ref', 'rb-s3-integration-ref',
      '--context', contextFile,
      '--all-harnesses',
    ]);
    assert.strictEqual(result.status, 0, `assembly against bootstrapped target failed: ${result.stderr}`);

    const files = readHarnessFiles(tmp);
    for (const rel of HARNESS_FILES) {
      assert.ok(files[rel] !== null, `expected ${rel} to be generated against the bootstrapped target`);
    }
    const reference = files[HARNESS_FILES[0]].toString('utf8');
    for (const rel of HARNESS_FILES.slice(1)) {
      assert.ok(files[rel].equals(files[HARNESS_FILES[0]]), `${rel} is not byte-identical to ${HARNESS_FILES[0]}`);
    }
    assert.ok(reference.includes('/discovery'), 'assembled content should reference a real skill (discovery), not a fixture placeholder');
    assert.ok(!reference.includes('skill file not found'), 'assembled content should not contain missing-skill warnings');
  } finally {
    rmtmp(tmp);
  }
});

