test('driftCheckFails_whenOneFileHandEdited_namesWhichOne', () => {
  const tmp = mktmp();
  const ctxFile = writeTmpContext('meta:\n  name: "fixture-drift-dirty"\n');
  try {
    const assembled = runAssembly(tmp, [
      '--skills-repo-path', ROOT,
      '--ref', 'rb-s3-test-ref',
      '--context', ctxFile,
      '--all-harnesses',
    ]);
    assert.strictEqual(assembled.status, 0, `assembly setup failed: ${assembled.stderr}`);

    const cursorrulesPath = path.join(tmp, '.cursorrules');
    fs.appendFileSync(cursorrulesPath, '\n# hand-edited line — should be caught by drift-check\n');

    const { checkDrift } = require('../scripts/check-instructions-drift');
    const result = checkDrift(tmp);
    assert.strictEqual(result.ok, false, 'expected drift check to fail after hand-editing .cursorrules');
    assert.deepStrictEqual(result.divergent, ['.cursorrules'], 'divergent file list should name exactly .cursorrules');

    const cliResult = spawnSync(process.execPath, [DRIFT_CHECK_SCRIPT, '--dir', tmp], { encoding: 'utf8' });
    assert.notStrictEqual(cliResult.status, 0, 'CLI drift-check should exit non-zero when a file has diverged');
    assert.ok(cliResult.stderr.includes('.cursorrules') || cliResult.stdout.includes('.cursorrules'),
      'drift-check output should name .cursorrules specifically, not a generic "drift detected"');
  } finally {
    rmtmp(tmp);
    try { fs.unlinkSync(ctxFile); } catch (_) {}
  }
});

