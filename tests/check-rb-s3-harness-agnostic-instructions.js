'use strict';

const assert = require('assert');
const fs = require('fs');
const path = require('path');
const os = require('os');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const ASSEMBLE_SCRIPT = path.join(ROOT, 'scripts', 'assemble-copilot-instructions.sh');
const DRIFT_CHECK_SCRIPT = path.join(ROOT, 'scripts', 'check-instructions-drift.js');
const CONTEXT_GITHUB_FIXTURE = path.join(ROOT, 'tests', 'fixtures', 'context-github.yml');

let passed = 0;
let failed = 0;

function test(name, fn) {
  try {
    fn();
    console.log(`  ✔ ${name}`);
    passed++;
  } catch (err) {
    console.error(`  ✖ ${name}`);
    console.error(`    ${err.message}`);
    failed++;
  }
}

function mktmp() {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'rb-s3-test-'));
}

function rmtmp(dir) {
  try { fs.rmSync(dir, { recursive: true, force: true }); } catch (_) {}
}

// Node wrapper for testability, mirroring the existing pattern already used
// by .github/scripts/check-assembly.js's runAssemblyInTmpDir — invoking the
// bash script via spawnSync rather than reimplementing its assembly logic in
// a second, parallel JS mechanism (explicitly disallowed by this story's
// Architecture Constraints).
const bashBin = (() => {
  if (process.platform !== 'win32') return 'bash';
  const gitBash = 'C:\\Program Files\\Git\\bin\\bash.exe';
  if (fs.existsSync(gitBash)) return gitBash;
  return 'bash';
})();

function runAssembly(cwd, args) {
  return spawnSync(bashBin, [ASSEMBLE_SCRIPT].concat(args || []), {
    cwd,
    encoding: 'utf8',
    env: Object.assign({}, process.env, { NO_COLOR: '1' }),
  });
}

function writeTmpContext(content) {
  const tmpFile = path.join(os.tmpdir(), `rb-s3-ctx-${Date.now()}-${Math.random().toString(36).slice(2)}.yml`);
  fs.writeFileSync(tmpFile, content, 'utf8');
  return tmpFile;
}

const HARNESS_FILES = [
  'CLAUDE.md',
  'AGENTS.md',
  '.cursorrules',
  path.join('.github', 'copilot-instructions.md'),
];

function readHarnessFiles(dir) {
  const out = {};
  for (const rel of HARNESS_FILES) {
    const full = path.join(dir, rel);
    out[rel] = fs.existsSync(full) ? fs.readFileSync(full) : null;
  }
  return out;
}

